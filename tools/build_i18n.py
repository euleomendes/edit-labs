#!/usr/bin/env python3
"""Builds i18n.js (the editor's English and Spanish UI) from tools/i18n.tsv.
Each TSV line: Portuguese<TAB>English<TAB>Spanish. Run: python3 tools/build_i18n.py"""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
en, es = {}, {}
for ln in open(os.path.join(root, 'tools', 'i18n.tsv'), encoding='utf-8'):
    ln = ln.rstrip('\n')
    if not ln.strip() or ln.startswith('#'): continue
    pt, e, s = ln.split('\t')
    en[pt] = e; es[pt] = s
engine = open(os.path.join(root, 'tools', 'i18n_engine.js'), encoding='utf-8').read()
out = ('// Generated by tools/build_i18n.py from tools/i18n.tsv. Edit the TSV, then run the script.\n'
       'window.I18N_DICT = ' + json.dumps({'en': en, 'es': es}, ensure_ascii=False, separators=(',', ':')) + ';\n' + engine)
open(os.path.join(root, 'i18n.js'), 'w', encoding='utf-8').write(out)
print(len(en), 'strings')
